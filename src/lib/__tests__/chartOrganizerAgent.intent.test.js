import { describe, it, expect } from "vitest";
import { isChartOrganizeRequest } from "../chartOrganizerAgent.js";

describe("isChartOrganizeRequest", () => {
  it("يكتشف صياغات عربية طبيعية متنوعة لطلب تنظيم شجرة حسابات (بفعل تنظيم صريح)", () => {
    const positives = [
      "نظملي شجرة الحسابات هذي",
      "ممكن ترتب لي شجرة الحسابات المرفقة؟",
      "أبغى تنظيم الحسابات بهذا الملف حسب قيود",
      "رجاءً رتّب دليل الحسابات المرفق وجهزه للرفع",
      "صنف لي الحسابات الموجودة بالملف",
      "نسق شجرتي وخلها جاهزة للرفع بقيود",
    ];
    positives.forEach((text) => expect(isChartOrganizeRequest(text), text).toBe(true));
  });

  // إصلاح خطأ جوهري حقيقي: رسائل طبيعية جداً تصف الملف بدل أن تأمر بفعل تنظيم
  // صريح (بلا "نظّم/رتّب/صنّف...") كانت تفوّت الشرط القديم فتذهب لمسار الدردشة
  // العام (Gemini النصي) الذي لا يستطيع توليد ملف حقيقي - فيردّ بنص "منجَز"
  // وهمي بلا أي ملف فعلي (حالة حقيقية أكّدها المستخدم). المستدعي الوحيد في
  // chat.jsx يتحقق أصلاً من وجود جدول بيانات مرفَق قبل استدعاء هذه الدالة،
  // فذِكر شجرة/حسابات في النص وحده كافٍ الآن.
  it("يكتشف أيضاً وصفاً للملف بلا فعل تنظيم صريح (الحالة الحقيقية التي فشلت)", () => {
    const positives = [
      "هذا الملف هو لشجرة غير منظمة ومتداخلة وخصوم والتزامات مع بعض بيانات قيود",
      "هذا شجرة حسابات العميل، ارفعها على قيود كقالب",
      "مرفق دليل الحسابات الخاص بالعميل",
      "فيه مشكلة بترميز أسماء الحسابات بهذا الملف",
    ];
    positives.forEach((text) => expect(isChartOrganizeRequest(text), text).toBe(true));
  });

  it("لا يستجيب لطلبات جدول بيانات عامة لا علاقة لها بشجرة/دليل حسابات على الإطلاق", () => {
    const negatives = [
      "احذف الأعمدة الفارغة من هذا الملف",
      "رتب الصفوف تصاعدياً حسب التاريخ",
      "افصل هذا الشيت حسب الفرع",
      "لخص لي هذا الملف",
      "",
      "مرحبا كيف حالك",
    ];
    negatives.forEach((text) => expect(isChartOrganizeRequest(text), text).toBe(false));
  });
});
