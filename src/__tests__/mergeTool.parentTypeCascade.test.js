import { describe, it, expect } from "vitest";
import { applyRowPatch, cascadeParentTypeChange, pickTypeWithinCategory, LEVEL3_MAP } from "../MergeTool.jsx";

/**
 * [طلب صريح من المستخدم 2026-10-08] تعديل نوع حساب أب ينزل تلقائياً على
 * أبنائه (بالمخطط والتعديل اليدوي) — مثال الصورة: الحساب 41 (م2) غُيّر من
 * "الإيرادات الأخرى" إلى "المبيعات" فبقي أبناؤه "إيرادات أخرى" بخطأ أحمر.
 */
const row = (id, code, nameAr, level, parent, type, level2Category = "", extra = {}) => ({
  id, status: "new", code, nameAr, nameEn: "", level, parent, type, level2Category,
  deleted: false, autoParent: false, errors: [], warnings: [], payCollect: "No", desc: "", source: {}, ...extra,
});
const mismatch = (cat) => [`توافق النوع مع الأب: النوع الحالي "إيرادات أخرى" لا يتبع عائلة الحساب الأب "41" (${cat})`];
const tree1Index = [{ code: "4", nameAr: "الإيرادات", parent: "", level: 1, type: "", level2Category: null }];
const by = (rows) => Object.fromEntries(rows.map((r) => [r.code, r]));

const screenshotRows = () => [
  row("p", "41", "الإيرادات التشغيلية", 2, "4", "الإيرادات الأخرى"),
  ...[["4102", "إيرادات تقديم خدمات أخرى"], ["4103", "إيرادات المبيعات"], ["4104", "الخصم المسموح به"],
    ["4105", "الخصم على المبيعات"], ["4106", "مردودات تقديم الخدمات"], ["4107", "مردودات تقديم خدمات أخرى"],
    ["4108", "مردودات المبيعات"], ["4109", "إيرادات تشغيلية أخرى"]]
    .map(([code, name]) => row(`c${code}`, code, name, 3, "41", "إيرادات أخرى", "الإيرادات الأخرى", { errors: [] })),
  row("g1", "410401", "خصم نقدي", 4, "4104", "إيرادات أخرى", "الإيرادات الأخرى"),
  row("g2", "410801", "مردودات نقدية", 4, "4108", "إيرادات أخرى", "الإيرادات الأخرى"),
];

describe("تسلسل نوع الأب لأبنائه", () => {
  it("سيناريو الصورة: 41 (م2) إلى المبيعات => كل الأبناء والأحفاد مبيعات بلا أي خطأ", () => {
    const rows = screenshotRows().map((r) => (r.level === 3 ? { ...r, errors: mismatch("المبيعات") } : r));
    const out = by(applyRowPatch(rows, "p", { type: "المبيعات" }, tree1Index));
    expect(out["41"].type).toBe("المبيعات");
    ["4102", "4103", "4104", "4105", "4106", "4107", "4108", "4109", "410401", "410801"].forEach((c) => {
      expect(out[c].type).toBe("المبيعات");
      expect(out[c].level2Category).toBe("المبيعات");
      expect(out[c].errors).toEqual([]);
    });
  });

  it("م2 إلى فئة متعددة الأنواع: الابن يُختار نوعه من اسمه داخل الفئة الجديدة فقط", () => {
    const rows = [
      row("p", "52", "مصاريف", 2, "5", "التكلفة المباشرة"),
      row("a", "5201", "رواتب الموظفين", 3, "52", "تكلفة المبيعات", "التكلفة المباشرة"),
      row("b", "5202", "مصاريف متنوعة", 3, "52", "تكاليف مباشرة أخرى", "التكلفة المباشرة"),
    ];
    const out = by(applyRowPatch(rows, "p", { type: "تكاليف تشغيلية" }, []));
    expect(out["5201"].type).toBe("الرواتب");
    expect(LEVEL3_MAP["تكاليف تشغيلية"]).toContain(out["5202"].type);
    expect(out["5201"].level2Category).toBe("تكاليف تشغيلية");
  });

  it("أب م3 يغيّر نوعه بنفس الفئة: الأبناء بنفس نوعه القديم يتبعونه، والابن بنوع مختلف صالح يبقى", () => {
    const rows = [
      row("p", "5201", "مصاريف إدارية", 3, "52", "مصاريف عمومية وإدارية", "تكاليف تشغيلية"),
      row("a", "520101", "إيجار المكتب", 4, "5201", "مصاريف عمومية وإدارية", "تكاليف تشغيلية"),
      row("b", "520102", "رواتب الإدارة", 4, "5201", "الرواتب", "تكاليف تشغيلية"),
    ];
    const out = by(applyRowPatch(rows, "p", { type: "تكاليف تشغيلية أخرى" }, []));
    expect(out["520101"].type).toBe("تكاليف تشغيلية أخرى");
    expect(out["520102"].type).toBe("الرواتب");
  });

  it("أب م3 ينتقل لفئة أخرى: كل أبنائه وأحفاده يأخذون نوعه", () => {
    const rows = [
      row("p", "4101", "إيرادات الخدمات", 3, "41", "إيرادات أخرى", "الإيرادات الأخرى"),
      row("a", "410101", "خدمات صيانة", 4, "4101", "إيرادات أخرى", "الإيرادات الأخرى"),
      row("b", "410102", "بيع أصول", 4, "4101", "مكاسب/خسائر بيع أصول", "الإيرادات الأخرى"),
      row("c", "41010101", "صيانة دورية", 5, "410101", "إيرادات أخرى", "الإيرادات الأخرى"),
    ];
    const out = by(applyRowPatch(rows, "p", { type: "المبيعات" }, []));
    ["410101", "410102", "41010101"].forEach((c) => {
      expect(out[c].type).toBe("المبيعات");
      expect(out[c].level2Category).toBe("المبيعات");
    });
  });

  it("تغيير الفئة فقط (النوع يفرغ) ثم اختيار النوع: الأبناء يتبعون النوع المختار بالخطوة الثانية", () => {
    const rows = [
      row("p", "5201", "مصاريف عامة", 3, "52", "تكلفة المبيعات", "التكلفة المباشرة"),
      row("a", "520101", "قرطاسية", 4, "5201", "تكلفة المبيعات", "التكلفة المباشرة"),
    ];
    const step1 = applyRowPatch(rows, "p", { level2Category: "تكاليف تشغيلية", type: "" }, []);
    expect(LEVEL3_MAP["تكاليف تشغيلية"]).toContain(by(step1)["520101"].type);
    expect(by(step1)["520101"].level2Category).toBe("تكاليف تشغيلية");
    const step2 = by(applyRowPatch(step1, "p", { type: "مصاريف عمومية وإدارية" }, []));
    expect(step2["520101"].type).toBe("مصاريف عمومية وإدارية");
  });

  it("تعديل يدوي على نوع الابن بعدها يُحترم ولا يُلغيه تعديل لاحق للأب داخل نفس الفئة", () => {
    let rows = [
      row("p", "5201", "مصاريف", 3, "52", "مصاريف عمومية وإدارية", "تكاليف تشغيلية"),
      row("a", "520101", "إعلانات", 4, "5201", "مصاريف عمومية وإدارية", "تكاليف تشغيلية"),
    ];
    rows = applyRowPatch(rows, "p", { type: "تكاليف تشغيلية أخرى" }, []);
    expect(by(rows)["520101"].type).toBe("تكاليف تشغيلية أخرى");
    rows = applyRowPatch(rows, "a", { type: "مصاريف تسويقية" }, []);
    rows = applyRowPatch(rows, "p", { type: "الرواتب" }, []);
    expect(by(rows)["520101"].type).toBe("مصاريف تسويقية");
    expect(by(rows)["5201"].type).toBe("الرواتب");
  });

  it("تعديل لا يمس النوع (الاسم) لا يغيّر أي ابن", () => {
    const rows = screenshotRows();
    const out = applyRowPatch(rows, "p", { nameAr: "اسم جديد" }, tree1Index);
    out.filter((r) => r.id !== "p").forEach((r, i) => expect(r).toBe(rows.filter((x) => x.id !== "p")[i]));
  });

  it("النقل بالسحب يغيّر رمز الأب بنفس الاستدعاء: الأبناء (ما زالوا على الرمز القديم) يتبعون", () => {
    const rows = [
      row("p", "4201", "إيرادات متنوعة", 3, "42", "إيرادات أخرى", "الإيرادات الأخرى"),
      row("a", "420101", "إيراد خدمات", 4, "4201", "إيرادات أخرى", "الإيرادات الأخرى"),
    ];
    const out = by(applyRowPatch(rows, "p", { parent: "41", code: "4110", level: 3, type: "المبيعات", level2Category: "المبيعات" }, []));
    expect(out["4110"].type).toBe("المبيعات");
    expect(out["420101"].type).toBe("المبيعات");
  });

  it("المحذوف (المستبعد) لا يُلمس، والسلسلة محمية من الحلقات", () => {
    const rows = [
      row("p", "41", "أ", 2, "4", "الإيرادات الأخرى"),
      row("a", "4101", "ب", 3, "41", "إيرادات أخرى", "الإيرادات الأخرى", { deleted: true }),
      row("x", "4102", "ج", 3, "4103", "إيرادات أخرى", "الإيرادات الأخرى"),
      row("y", "4103", "د", 3, "4102", "إيرادات أخرى", "الإيرادات الأخرى"),
    ];
    const { rows: out } = cascadeParentTypeChange(applyRowPatch(rows, "p", { type: "المبيعات" }, []), "x", { oldCode: "4102", oldType: "إيرادات أخرى" });
    expect(by(out)["4101"].type).toBe("إيرادات أخرى");
  });

  it("pickTypeWithinCategory: نوع الأب المفضّل لو صالح، وإلا نوعه الحالي، وإلا من الاسم، وإلا الافتراضي", () => {
    expect(pickTypeWithinCategory({ type: "الرواتب" }, "تكاليف تشغيلية", "مصاريف تسويقية")).toBe("مصاريف تسويقية");
    expect(pickTypeWithinCategory({ type: "الرواتب" }, "تكاليف تشغيلية", "تكاليف تشغيلية")).toBe("الرواتب");
    expect(pickTypeWithinCategory({ type: "", nameAr: "رواتب الموظفين" }, "تكاليف تشغيلية")).toBe("الرواتب");
    expect(pickTypeWithinCategory({ type: "", nameAr: "شيء" }, "المبيعات")).toBe("المبيعات");
  });
});
